function caparol_info( $key = '' ) {

	$info = array(

		/* ── 여기부터 실제 값으로 바꿔주세요 ──────────────── */

		'company'   => '카파롤코리아',
		'ceo'       => '',                       // 대표자명
		'biz_no'    => '',                       // 사업자등록번호  예: 123-45-67890
		'address'   => '',                       // 주소
		'tel'       => '02-000-0000',            // 대표전화 (화면 표시용)
		'fax'       => '',
		'email'     => '',                       // 대표 이메일
		'hours'     => '평일 09:00 – 18:00 (점심 12:00 – 13:00)',
		'kakao'     => '',                       // 카카오톡 채널 URL

		// 문의 폼이 도착할 메일 주소. 비워두면 워드프레스 관리자 메일로 갑니다.
		'inquiry_to' => '',

		/* ── 여기까지 ─────────────────────────────────────── */

		'tagline'   => '독일 Caparol 제품을 직접 수입·공급하는 한국 공식 법인입니다.',
	);

	// 전화번호에서 하이픈을 뺀 값 — tel: 링크용
	$info['tel_raw'] = preg_replace( '/[^0-9+]/', '', $info['tel'] );

	if ( '' === $key ) {
		return $info;
	}

	return isset( $info[ $key ] ) ? $info[ $key ] : '';
}
